"""Разбор и сравнение версий программ."""


def parse(version: str) -> tuple[int, ...]:
    """
    Преобразовать строку версии в кортеж чисел для сравнения.

    Нули в конце отбрасываются, поэтому "15" == "15.0.0".
    Количество чисел в версии не ограничено.

    Аргументы:
        version: строка из чисел, разделённых точками

    Вывод:
        Кортеж целых чисел. Для "0" результат пустой кортеж

    Исключения:
        ValueError: Если какая-то часть не является числом
    """
    parts = [int(p) for p in version.split(".")]
    while parts and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def is_vulnerable(version: str, start: str, fixed: str) -> bool:
    """
    Проверить, что версия входит в уязвимый диапазон.

    Граница start входит в диапазон, а граница fixed нет:
    в версии fixed уязвимость уже исправлена.

    Аргументы:
        version: Проверяемая версия
        start: Первая версия, в которой выявлена уязвимость
        fixed: Первая исправленная версия

    Вывод:
        True, если версия попадает в уязвимый диапазон
    """
    return parse(start) <= parse(version) < parse(fixed)
